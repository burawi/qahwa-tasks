import assert from "node:assert/strict";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { documentFromPlainText } from "../src/domain/types.js";
import { AppDatabase } from "../src/server/database.js";
import { TaskService } from "../src/server/task-service.js";
import { AuthService } from "../src/server/auth.js";
import { buildApp } from "../src/server/app.js";
import { searchTasks } from "../src/web/task-search.js";

test("search covers complete scoped lists, descriptions and sessions without changing order or data", async () => {
  const root = mkdtempSync(join(tmpdir(), "qahwa-search-"));
  const config = { host: "127.0.0.1", port: 0, publicBaseUrl: "http://localhost", dataDir: root, backupDir: join(root, "backups"), sessionDays: 1 };
  const database = new AppDatabase(config);
  const service = new TaskService(database);
  const project = service.createProject({ name: "Café Workspace", prefix: "FIND", rootDirectory: root }, "user");
  const other = service.createProject({ name: "Other", prefix: "OTH", rootDirectory: root }, "user");
  const create = (title: string, projectId = project.id) => service.createTask({ projectId, title, status: "todo", description: documentFromPlainText("Deep\n description\tneedle 100% [literal]") }, "user");
  const old = create("Oldest matching entry");
  for (let i = 0; i < 125; i++) create(`Matching entry ${i}`);
  const terminal = create("Matching terminal session");
  database.db.prepare("UPDATE tasks SET session_kind = 'terminal' WHERE id = ?").run(terminal.id);
  const foreign = create("Matching foreign", other.id);
  const closed = create("Matching history");
  service.transition(closed.id, { to: "closed", outcome: "cancelled" }, "user");
  service.setPinned(old.id, true);
  database.db.prepare("INSERT INTO chat_messages(id,owner_type,owner_id,role,body,created_at) VALUES ('reply','task',?,'assistant','messageonlysecret','2026-10-31')").run(old.id);
  const app = await buildApp(config, database);
  try {
    const url = `/api/tasks?tab=active&order=conversation&projectId=${project.id}`;
    assert.equal((await app.inject({ method: "GET", url })).statusCode, 401);
    database.db.prepare("INSERT INTO paired_devices(id,name,public_key,created_at,last_seen_at) VALUES ('search','Search','','now','now')").run();
    const headers = { authorization: `Bearer ${new AuthService(database, 1).createSession("test", "127.0.0.1", "search").token}` };
    const response = await app.inject({ method: "GET", url, headers });
    assert.equal(response.statusCode, 200);
    const list = response.json().tasks;
    const snapshot = JSON.stringify(list);
    const queueBefore = service.listTasks({ tab: "active" });
    const ids = (query: string) => searchTasks(list, query).map(t => t.id);
    assert.equal(list.length, 127);
    assert.deepEqual(ids(" matching "), list.map((t: { id: string }) => t.id));
    assert.deepEqual(ids("oldest"), [old.id]);
    assert.deepEqual(ids(old.humanId.toLowerCase()), [old.id]);
    assert.deepEqual(ids("  CAFÉ\n  oldest \t"), [old.id], "Words can span metadata fields");
    assert.deepEqual(ids("cafe\u0301"), list.map((t: { id: string }) => t.id), "Canonical Unicode is normalized");
    assert.deepEqual(ids("deep DESCRIPTION needle"), list.map((t: { id: string }) => t.id));
    assert.deepEqual(ids("100% [literal]"), list.map((t: { id: string }) => t.id));
    assert.deepEqual(ids("terminal"), [terminal.id]);
    for (const query of ["messageonlysecret", "history", "foreign", "paragraph", "missing"]) assert.deepEqual(ids(query), []);
    assert.equal(searchTasks(list, " \n\t "), list);
    assert.equal(JSON.stringify(list), snapshot);
    assert.deepEqual(service.listTasks({ tab: "active" }), queueBefore);
    assert.equal(list[0].conversation.unreadCount, 1);
    assert.deepEqual(searchTasks(service.listTasks({ tab: "closed", projectId: project.id, order: "conversation" }), "matching").map(t => t.id), [closed.id]);
    assert.deepEqual(searchTasks(service.listTasks({ tab: "active", projectId: other.id, order: "conversation" }), "matching").map(t => t.id), [foreign.id]);
    service.updateTask(old.id, { title: "Renamed", description: documentFromPlainText("Changed description"), expectedVersion: old.version }, "user");
    const next = (await app.inject({ method: "GET", url, headers })).json().tasks;
    assert.deepEqual(searchTasks(next, "renamed changed").map(t => t.id), [old.id]);
  } finally { await app.close(); rmSync(root, { recursive: true, force: true }); }
});
